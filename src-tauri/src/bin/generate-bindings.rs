//! Regenerates `src/lib/ipc/bindings.ts` without launching the GUI.
//! CI runs this before typecheck so committed bindings can never drift:
//! `cargo run --bin generate-bindings`. The command/event registry MUST stay
//! in sync with `run()` in lib.rs.
//!
//! `run()` re-exports the same bindings on every debug launch.
use specta_typescript::Typescript;
use tauri_specta::{collect_commands, collect_events, Builder, ErrorHandlingMode};

fn main() {
    let builder = Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            easy_git::commands::app_version,
            easy_git::commands::env_check,
            easy_git::commands::repo_open,
            easy_git::commands::repo_init,
            easy_git::commands::repo_close,
            easy_git::commands::status_get,
            easy_git::commands::stage,
            easy_git::commands::discard_changes,
            easy_git::commands::clean_preview,
            easy_git::commands::clean_execute,
            easy_git::commands::ignore_paths,
            easy_git::commands::undo_operation,
            easy_git::commands::commit,
            easy_git::commands::config_get,
            easy_git::commands::config_set,
            easy_git::commands::log_page,
            easy_git::commands::commit_detail,
            easy_git::commands::list_branches,
            easy_git::commands::diff_file,
            easy_git::commands::stage_lines,
            easy_git::commands::branch_list,
            easy_git::commands::branch_create,
            easy_git::commands::branch_rename,
            easy_git::commands::branch_delete,
            easy_git::commands::branch_switch,
            easy_git::commands::tag_list,
            easy_git::commands::tag_create,
            easy_git::commands::tag_delete,
            easy_git::commands::stash_list,
            easy_git::commands::stash_push,
            easy_git::commands::stash_apply,
            easy_git::commands::stash_drop,
            easy_git::commands::merge_start,
            easy_git::commands::merge_state,
            easy_git::commands::merge_abort,
            easy_git::commands::conflicts_get,
            easy_git::commands::conflict_resolve,
            easy_git::commands::revert_commits,
            easy_git::commands::reset_commits,
            easy_git::commands::sync_fetch,
            easy_git::commands::sync_pull,
            easy_git::commands::sync_push,
            easy_git::commands::remote_test,
            easy_git::commands::repo_clone,
            easy_git::commands::remote_list,
            easy_git::commands::remote_add,
            easy_git::commands::remote_rename,
            easy_git::commands::remote_remove,
            easy_git::commands::remote_set_url,
            easy_git::commands::redo_operation,
            easy_git::commands::timeline_get,
            easy_git::commands::timeline_restore,
            easy_git::commands::branch_set_upstream,
            easy_git::commands::undo_redo_state,
            easy_git::commands::remote_branch_list,
            easy_git::commands::logs_dir,
            easy_git::commands::logs_list,
            easy_git::commands::logs_read,
            easy_git::commands::log_write,
        ])
        .events(collect_events![
            easy_git::events::RepoChanged,
            easy_git::events::SyncProgressEvent
        ])
        .error_handling(ErrorHandlingMode::Result);

    builder
        .export(
            Typescript::default().header("// @generated by tauri-specta. DO NOT EDIT.\n"),
            "../src/lib/ipc/bindings.ts",
        )
        .expect("failed to export tauri-specta bindings");
}
