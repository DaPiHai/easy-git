//! Regenerates `src/lib/ipc/bindings.ts` without launching the GUI.
//! CI runs this before typecheck so committed bindings can never drift:
//! `cargo run --bin generate-bindings`. The command/event registry MUST stay
//! in sync with `run()` in lib.rs.
//!
//! `run()` re-exports the same bindings on every debug launch.
use specta_typescript::Typescript;
use tauri_specta::{collect_commands, collect_events, Builder, ErrorHandlingMode};

fn main() {
    let builder = Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            easy_git::commands::app_version,
            easy_git::commands::repo_open,
            easy_git::commands::repo_init,
            easy_git::commands::repo_close,
            easy_git::commands::status_get,
            easy_git::commands::stage,
            easy_git::commands::discard_changes,
            easy_git::commands::clean_preview,
            easy_git::commands::clean_execute,
            easy_git::commands::ignore_paths,
            easy_git::commands::undo_operation,
            easy_git::commands::commit,
            easy_git::commands::config_get,
            easy_git::commands::config_set,
            easy_git::commands::log_page,
            easy_git::commands::commit_detail,
            easy_git::commands::list_branches,
            easy_git::commands::diff_file,
            easy_git::commands::stage_lines,
        ])
        .events(collect_events![easy_git::events::RepoChanged])
        .error_handling(ErrorHandlingMode::Result);

    builder
        .export(
            Typescript::default().header("// @generated by tauri-specta. DO NOT EDIT.\n"),
            "../src/lib/ipc/bindings.ts",
        )
        .expect("failed to export tauri-specta bindings");
}
