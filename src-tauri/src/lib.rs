use eg_git_core::RepoManager;
use eg_safety::Safety;
use specta_typescript::Typescript;
use tauri::{Manager, RunEvent};
use tauri_specta::{collect_commands, collect_events, Builder, ErrorHandlingMode};
use tracing_subscriber::prelude::*;

/// Panics land in the same local log file as everything else (PRD §7: 崩溃
/// 日志本地存储), then the default hook still prints to stderr.
fn install_panic_hook() {
    let previous = std::panic::take_hook();
    std::panic::set_hook(Box::new(move |info| {
        let location = info
            .location()
            .map(|l| l.to_string())
            .unwrap_or_else(|| "unknown".into());
        tracing::error!(target: "panic", location, "{info}");
        previous(info);
    }));
}

/// App entry point. The Tauri window, the IPC command registry and the
/// tauri-specta type pipeline are wired here.
#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            commands::app_version,
            commands::env_check,
            commands::repo_open,
            commands::repo_init,
            commands::repo_close,
            commands::status_get,
            commands::stage,
            commands::discard_changes,
            commands::clean_preview,
            commands::clean_execute,
            commands::ignore_paths,
            commands::undo_operation,
            commands::commit,
            commands::config_get,
            commands::config_set,
            commands::log_page,
            commands::commit_detail,
            commands::list_branches,
            commands::diff_file,
            commands::stage_lines,
            commands::branch_list,
            commands::branch_create,
            commands::branch_rename,
            commands::branch_delete,
            commands::branch_switch,
            commands::tag_list,
            commands::tag_create,
            commands::tag_delete,
            commands::stash_list,
            commands::stash_push,
            commands::stash_apply,
            commands::stash_drop,
            commands::merge_start,
            commands::merge_state,
            commands::merge_abort,
            commands::conflicts_get,
            commands::conflict_resolve,
            commands::revert_commits,
            commands::reset_commits,
            commands::sync_fetch,
            commands::sync_pull,
            commands::sync_push,
            commands::remote_test,
            commands::repo_clone,
            commands::remote_list,
            commands::remote_add,
            commands::remote_rename,
            commands::remote_remove,
            commands::remote_set_url,
            commands::redo_operation,
            commands::timeline_get,
            commands::timeline_restore,
            commands::branch_set_upstream,
            commands::undo_redo_state,
            commands::remote_branch_list,
        ])
        .events(collect_events![
            events::RepoChanged,
            events::SyncProgressEvent
        ])
        .error_handling(ErrorHandlingMode::Result);

    // Regenerate TS bindings on every debug launch so they can never drift.
    #[cfg(debug_assertions)]
    builder
        .export(
            Typescript::default().header("// @generated by tauri-specta. DO NOT EDIT.\n"),
            "../src/lib/ipc/bindings.ts",
        )
        .expect("failed to export tauri-specta bindings");

    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_opener::init())
        .manage(RepoManager::default())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            // Local-only logging (TDD §7): stderr layer for dev consoles plus
            // a daily-rolling file under <app-data>/logs — the release GUI
            // binary has no console, so the file sink is the durable one.
            // `RUST_LOG` still overrides the default `info` filter.
            let app_data = app.path().app_data_dir().map_err(|e| e.to_string())?;
            let log_dir = logs::logs_dir(&app_data);
            std::fs::create_dir_all(&log_dir).map_err(|e| e.to_string())?;
            logs::cleanup_old_logs(&log_dir, logs::RETENTION_DAYS);
            let (file_writer, guard) = tracing_appender::non_blocking(
                tracing_appender::rolling::daily(&log_dir, logs::LOG_FILE_PREFIX),
            );
            tracing_subscriber::registry()
                .with(
                    tracing_subscriber::EnvFilter::try_from_default_env()
                        .unwrap_or_else(|_| tracing_subscriber::EnvFilter::new("info")),
                )
                .with(tracing_subscriber::fmt::layer().with_ansi(true))
                .with(
                    tracing_subscriber::fmt::layer()
                        .with_ansi(false)
                        .with_writer(file_writer),
                )
                .init();
            // Keep the background writer thread alive for the whole process.
            app.manage(guard);
            install_panic_hook();
            tracing::info!(version = env!("CARGO_PKG_VERSION"), "app starting");

            // Safety operation log lives under the app data dir (TDD §4.3).
            app.manage(Safety::new(&app_data));
            builder.mount_events(app);
            Ok(())
        })
        .build(tauri::generate_context!())
        .expect("error while building EasyGit")
        .run(|app_handle, event| {
            if let RunEvent::Exit = event {
                // Drain and stop every repo worker thread.
                app_handle.state::<RepoManager>().close_all();
            }
        });
}
